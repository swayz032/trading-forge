"""RENDER the ranking table, and VERIFY a rendered table against the structured
artifact.  AR-430 / R-454 §4(3).

WHY THIS EXISTS
    R-453 §3 minted: a report's table is an INSTRUMENT'S OUTPUT, not a
    transcription. AR-427 hand-normalized 40 rows during transcription and the
    published table silently diverged from the committed JSON.
    R-454 §4(3): '"Generated from the output" is a claim about the past; a check
    that REGENERATES and DIFFS is a property of the artifact.'

    So: `render` emits the table, and `--verify` regenerates it and diffs. A row
    edited by hand after generation FAILS the verify -- which is the whole point,
    and the test proves it by doing exactly that.

USAGE
    python unlock_rank_render.py <rank.json>                 # print the table
    python unlock_rank_render.py <rank.json> --out <file.md> # write it
    python unlock_rank_render.py <rank.json> --verify <file.md>   # regenerate + diff
"""

import hashlib
import json
import sys

COLUMNS = [("rank", "#"), ("canonical_video_id", "video"), ("distance", "dist"),
           ("residual_conditions", "resid"), ("fixed_class_conditions", "C8"),
           ("total_conditions", "tot"), ("residual_classes", "residual classes"),
           ("spec", "spec (display only)")]


def sha256_file(path):
    with open(path, "rb") as fh:
        return hashlib.sha256(fh.read()).hexdigest()


def render(rank_path):
    with open(rank_path, encoding="utf-8") as fh:
        doc = json.load(fh)
    rows = doc if isinstance(doc, list) else doc["ranking"]
    pop = {} if isinstance(doc, list) else doc.get("population", {})

    out = []
    out.append("<!-- GENERATED by unlock_rank_render.py -- DO NOT EDIT BY HAND.")
    out.append("     Verify with: python unlock_rank_render.py <rank.json> --verify <this file>")
    out.append(f"     source sha256: {sha256_file(rank_path)} -->")
    out.append("")
    out.append("# UNLOCK-DISTANCE RANKING — `POP-120-LIVE` under the {C8-fixed} counterfactual")
    out.append("")
    if pop:
        out.append(f"**Population:** {pop.get('videos')} distinct source videos · "
                   f"{pop.get('rows')} rows · replication ×{pop.get('replication_factor')} · "
                   f"`backtests_total = {pop.get('backtests_total')}`")
        out.append("")
    out.append("**`canonical_video_id` is the IDENTITY. `spec` is a DISPLAY field and is NOT "
               "unique — never key, join, dedupe or count on it (R-454 §3).**")
    out.append("")
    out.append("| " + " | ".join(h for _, h in COLUMNS) + " |")
    out.append("|" + "|".join("---" for _ in COLUMNS) + "|")
    for r in rows:
        cells = []
        for key, _ in COLUMNS:
            v = r.get(key)
            if isinstance(v, list):
                v = ",".join(str(x) for x in v) or "—"
            cells.append(f"`{v}`" if key in ("canonical_video_id", "spec") else str(v))
        out.append("| " + " | ".join(cells) + " |")
    out.append("")
    return "\n".join(out) + "\n"


def main():
    if len(sys.argv) < 2:
        raise SystemExit(__doc__)
    rank_path = sys.argv[1]
    if "--verify" in sys.argv:
        target = sys.argv[sys.argv.index("--verify") + 1]
        with open(target, encoding="utf-8") as fh:
            actual = fh.read()
        expected = render(rank_path)
        if actual == expected:
            print(f"REPORT-INTEGRITY OK: {target} regenerates byte-identically from {rank_path}")
            return 0
        a, e = actual.splitlines(), expected.splitlines()
        print(f"REPORT-INTEGRITY FAILED: {target} does NOT match a regeneration from {rank_path}")
        if len(a) != len(e):
            print(f"  line count {len(a)} (file) vs {len(e)} (regenerated)")
        shown = 0
        for i, (x, y) in enumerate(zip(a, e), 1):
            if x != y:
                print(f"  line {i}:\n    file        : {x}\n    regenerated : {y}")
                shown += 1
                if shown >= 5:
                    print("  ... further differences suppressed")
                    break
        return 1
    text = render(rank_path)
    if "--out" in sys.argv:
        out = sys.argv[sys.argv.index("--out") + 1]
        with open(out, "w", encoding="utf-8", newline="\n") as fh:
            fh.write(text)
        print(f"wrote {out}")
        return 0
    sys.stdout.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
